-- ── Profiles (one per login) ───────────────────────────────
create table public.profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  full_name  text,
  email      text,
  phone      text,
  role       text not null default 'staff' check (role in ('admin','staff')),
  created_at timestamptz not null default now()
);

-- Auto-create a profile whenever a user is added in Authentication
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name, email)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)), new.email);
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql security definer stable set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- ── Jobs ───────────────────────────────────────────────────
create table public.jobs (
  id             bigint generated by default as identity (start with 1001) primary key,
  title          text not null,
  description    text,
  address        text not null,
  client         text,
  tenant_name    text,
  tenant_phone   text,
  tenant_email   text,
  scheduled_date date not null default current_date,
  start_time     time,
  end_time       time,
  assigned_to    uuid references public.profiles(id) on delete set null,
  status         text not null default 'scheduled'
                 check (status in ('scheduled','on_the_way','in_progress','on_hold','completed')),
  photos         text[] not null default '{}',
  created_by     uuid references public.profiles(id) on delete set null,
  created_at     timestamptz not null default now(),
  completed_at   timestamptz
);
create index jobs_assigned_idx on public.jobs (assigned_to, scheduled_date);

-- ── Job activity (status changes, notes, completion) ───────
create table public.job_updates (
  id         bigint generated by default as identity primary key,
  job_id     bigint not null references public.jobs(id) on delete cascade,
  author_id  uuid references public.profiles(id) on delete set null,
  kind       text not null check (kind in ('created','status','note','completed','kept_open')),
  status     text,
  message    text,
  photos     text[] not null default '{}',
  created_at timestamptz not null default now()
);
create index job_updates_job_idx on public.job_updates (job_id);

-- ── Parts / material orders ────────────────────────────────
create table public.parts (
  id           bigint generated by default as identity primary key,
  job_id       bigint not null references public.jobs(id) on delete cascade,
  description  text not null,
  qty          int not null default 1,
  notes        text,
  status       text not null default 'requested' check (status in ('requested','ordered','received')),
  requested_by uuid references public.profiles(id) on delete set null,
  created_at   timestamptz not null default now()
);
create index parts_job_idx on public.parts (job_id);

-- ═══ Row Level Security ════════════════════════════════════
--  Every signed-in team member sees ALL jobs, so the team can help each other.
--  Staff can update status, add notes/photos and request parts on any job.
--  Only admin (manager) can create, edit details, delete jobs and manage parts orders.
alter table public.profiles    enable row level security;
alter table public.jobs        enable row level security;
alter table public.job_updates enable row level security;
alter table public.parts       enable row level security;

create policy "profiles: read all"      on public.profiles for select to authenticated using (true);
create policy "profiles: admin update"  on public.profiles for update to authenticated using (public.is_admin());
create policy "profiles: self update"   on public.profiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid() and role = (select role from public.profiles where id = auth.uid()));

create policy "jobs: read"   on public.jobs for select to authenticated using (true);
create policy "jobs: insert" on public.jobs for insert to authenticated with check (public.is_admin());
create policy "jobs: update" on public.jobs for update to authenticated using (true);
create policy "jobs: delete" on public.jobs for delete to authenticated using (public.is_admin());

-- Staff may only change a job's status; every other field stays as the manager set it.
create or replace function public.protect_job_fields()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  s  text        := new.status;
  ca timestamptz := new.completed_at;
begin
  if not public.is_admin() then
    new := old;
    new.status := s;
    new.completed_at := ca;
  end if;
  return new;
end $$;

create trigger jobs_protect_fields before update on public.jobs
  for each row execute function public.protect_job_fields();

create policy "updates: read"   on public.job_updates for select to authenticated using (true);
create policy "updates: insert" on public.job_updates for insert to authenticated with check (author_id = auth.uid());

create policy "parts: read"   on public.parts for select to authenticated using (true);
create policy "parts: insert" on public.parts for insert to authenticated with check (requested_by = auth.uid());
create policy "parts: admin update" on public.parts for update to authenticated using (public.is_admin());
create policy "parts: admin delete" on public.parts for delete to authenticated using (public.is_admin());

-- ═══ Photo storage (private bucket) ════════════════════════
insert into storage.buckets (id, name, public) values ('job-photos', 'job-photos', false)
on conflict (id) do nothing;

create policy "photos: read"   on storage.objects for select to authenticated using (bucket_id = 'job-photos');
create policy "photos: upload" on storage.objects for insert to authenticated with check (bucket_id = 'job-photos');
create policy "photos: delete" on storage.objects for delete to authenticated using (bucket_id = 'job-photos' and public.is_admin());

-- ═══ Realtime (lists refresh live on every phone) ══════════
alter publication supabase_realtime add table public.jobs, public.job_updates, public.parts;

